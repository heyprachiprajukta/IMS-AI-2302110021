import math
from cadquery import func as cf

def clutch_brick(length, width, height, stud_d, stud_h, spacing):

    # Create the main brick body
    body = cf.box(length, width, height)

    # Create one circular stud
    stud = cf.cylinder(d=stud_d, h=stud_h)

    # Add 8 studs using nested for loops
    brick = body

    for row in range(2):
        for col in range(4):

            x = (col - 1.5) * spacing
            y = (row - 0.5) * spacing

            new_stud = stud.moved(x=x, y=y, z=height)

            brick = brick + new_stud

    return brick


# Create a 2 x 4 clutch brick
brick = clutch_brick(31.2, 15.6, 9.6, 4.8, 1.7, 8.0)

# Calculate expected volume
body_volume = 31.2 * 15.6 * 9.6
stud_volume = 8 * math.pi * (4.8 / 2) ** 2 * 1.7

expected = body_volume + stud_volume

# Verify the volume
assert abs(brick.Volume() - expected) < 0.5

# Export the 3D model
brick.exportStl("brick.stl")

print("2 x 4 Clutch Brick created successfully!")
print("Number of studs: 8")
print("Expected volume:", expected)
print("Actual volume:", brick.Volume())
print("STL file exported successfully!")
